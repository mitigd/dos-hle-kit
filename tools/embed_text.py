#!/usr/bin/env python3
"""embed_text.py OUT.cpp SYMBOL=FILE... : emit a C++ file defining `const char* const SYMBOL` for each
text FILE, so data/ files travel inside the library (no runtime path lookups)."""
import sys

out, pairs = sys.argv[1], sys.argv[2:]
with open(out, 'w') as o:
    o.write('// generated by tools/embed_text.py\nnamespace hlekit::embedded {\n')
    for p in pairs:
        sym, path = p.split('=', 1)
        text = open(path).read()
        assert ')EMBED"' not in text
        o.write(f'extern const char* const {sym};\nconst char* const {sym} = R"EMBED({text})EMBED";\n')
    o.write('}  // namespace hlekit::embedded\n')
