#!/usr/bin/env python3
"""Derive data/fonts/hlekit-8x16.fnt from hlekit-8x8.fnt.

Each 8x8 row becomes two: the row itself, then a connecting row that keeps vertical strokes and
diagonals continuous while horizontal bars stay one pixel thick (as in a VGA 8x16 face):

    between(r, r+1) = (r & r+1) | (r+1 & (r<<1 | r>>1) & ~r)

The result is a starting point: edit the generated file by hand wherever a glyph wants it, and
keep it - this script refuses to overwrite a file that has no 'generated' marker.
"""
import os, sys

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', '..', 'data', 'fonts', 'hlekit-8x8.fnt')
dst = os.path.join(here, '..', '..', 'data', 'fonts', 'hlekit-8x16.fnt')
if os.path.exists(dst) and 'generated by tools/font/derive16.py' not in open(dst).read() and '--force' not in sys.argv:
    sys.exit(f'{dst} was edited by hand; pass --force to regenerate')

glyphs, order, cur = {}, [], None
for line in open(src).read().splitlines():
    if line.startswith('@ '):
        cur = line[2]; order.append(cur); glyphs[cur] = []
    elif cur is not None and line and not line.startswith(';') and not line.startswith('height'):
        glyphs[cur].append(int(''.join('1' if c == '#' else '0' for c in line.ljust(8, '.')), 2))

def bits(v): return ''.join('#' if v >> (7 - i) & 1 else '.' for i in range(8))

out = ['; hlekit 8x16 font, generated by tools/font/derive16.py from hlekit-8x8.fnt, then free to hand-edit.',
       '; Same format as hlekit-8x8.fnt.', 'height 16']
for ch in order:
    r = glyphs[ch] + [0] * (8 - len(glyphs[ch]))
    rows = []
    for i in range(8):
        a, b = r[i], r[i + 1] if i < 7 else 0
        rows.append(a)
        if i < 7:
            mid = (a & b) | (b & ((a << 1 | a >> 1) & 0xff) & ~a & 0xff)
        else:
            mid = 0
        rows.append(mid)
    # glyphs with a descender (row 7 set, or rows 6-7 set below the baseline) sit lower: shift the
    # whole body up two rows when row 7 is the only non-empty descender row so the baseline lands
    # on row 13 of 16, as in VGA text.
    while rows and rows[-1] == 0: rows.pop()
    out.append('@ ' + ch)
    out += [bits(v) for v in rows]
open(dst, 'w').write('\n'.join(out) + '\n')
